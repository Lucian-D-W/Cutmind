export function getLocaleCopy(language: AppLanguage) {
  return UI_COPY[language]
}

export function getDateLocale(language: AppLanguage) {
  return DATE_LOCALE_MAP[language]
}

export function formatMonthHeading(date: Date, language: AppLanguage) {
  return format(date, language === 'zh-CN' ? 'yyyy年M月' : 'MMMM yyyy', {
    locale: getDateLocale(language),
  })
}

export function formatDateTimeLabel(date: Date, language: AppLanguage) {
  return format(date, language === 'zh-CN' ? 'yyyy年M月d日 HH:mm' : 'MMM d, yyyy HH:mm', {
    locale: getDateLocale(language),
  })
}

export function formatHistoryLabel(date: Date, language: AppLanguage) {
  return format(date, language === 'zh-CN' ? 'M月d日 HH:mm' : 'MMM d HH:mm', {
    locale: getDateLocale(language),
  })
}

export function replaceTemplate(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ''))
}
